-- #2609 Precomputed user analytics store.
-- A nightly job writes one row per user per day (day) holding that day's
-- activity only (a per-day delta), so weekly/monthly/yearly figures are plain
-- SUM/COUNT roll-ups over this table without re-aggregating study_history on every request.
-- The live /admin/users endpoint is NOT served from here (it stays realtime, see #2971).

create table user_daily_analytics
(
    id             bigint generated by default as identity primary key,
    day            date      not null,
    user_id        bigint    not null,
    role_name      varchar(255) not null,
    first_done     timestamp,
    last_done      timestamp,
    spent_time     bigint,
    done_exercises integer,
    constraint user_daily_analytics_uq_user_role_day unique (user_id, role_name, day)
);

create index user_daily_analytics_ix_day on user_daily_analytics (day);
create index user_daily_analytics_ix_role_name on user_daily_analytics (role_name);
